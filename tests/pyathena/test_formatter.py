# A value whose single quote must not be allowed to terminate the string
# literal. Trino and Athena do not treat a backslash as an escape character
# inside a string literal, so a statement parsed by Trino must double the quote
# ('') rather than backslash-escape it (\').
HOSTILE = "a' OR 1=1 --"

# Statements parsed by the Trino/Athena engine, where single quotes must be
# doubled. DELETE and CTAS (CREATE TABLE ... AS SELECT) are the paths that
# CVE-2026-65321 left routed through the Hive escaper.
TRINO_STATEMENTS = [
    "SELECT * FROM t WHERE c = %(v)s",
    "WITH x AS (SELECT 1) SELECT * FROM t WHERE c = %(v)s",
    "INSERT INTO t VALUES (%(v)s)",
    "UPDATE t SET c = %(v)s",
    "MERGE INTO t USING s ON t.c = %(v)s",
    "DELETE FROM t WHERE c = %(v)s",
    "delete from t where c = %(v)s",
    "CREATE TABLE t WITH (format = 'PARQUET') AS SELECT * FROM s WHERE c = %(v)s",
    "CREATE VIEW v AS SELECT * FROM s WHERE c = %(v)s",
    "EXPLAIN DELETE FROM t WHERE c = %(v)s",
    "UNLOAD (SELECT * FROM t WHERE c = %(v)s) TO 's3://b/p/' WITH (format = 'PARQUET')",
    "/* generated by etl */ DELETE FROM t WHERE c = %(v)s",
    "-- nightly compaction\nDELETE FROM t WHERE c = %(v)s",
    "/* a */\n-- b\nDELETE FROM t WHERE c = %(v)s",
    "/* multi\nline */\nDELETE FROM t WHERE c = %(v)s",
    "\n\t DELETE FROM t WHERE c = %(v)s",
    # Near-miss statements: their prefixes are adjacent to the Hive allowlist
    # (ALTER/DROP/CREATE ... VIEW, VALUES) but Trino executes them, so they must
    # NOT be misrouted to the Hive escaper.
    "ALTER VIEW v AS SELECT name FROM s WHERE c = %(v)s",
    "DROP VIEW v -- %(v)s",
    "CREATE OR REPLACE VIEW v AS SELECT %(v)s",
    "VALUES (%(v)s)",
]

# Statements parsed by the Hive DDL engine, where backslash escaping is correct.
HIVE_STATEMENTS = [
    "CREATE EXTERNAL TABLE t (c string) LOCATION %(v)s",
    "CREATE TABLE t (c string) LOCATION %(v)s",
    "CREATE DATABASE d LOCATION %(v)s",
    "ALTER TABLE t SET LOCATION %(v)s",
    "DROP TABLE t PURGE -- %(v)s",
    "MSCK REPAIR TABLE t -- %(v)s",
    "SHOW PARTITIONS t -- %(v)s",
    "DESCRIBE t -- %(v)s",
    "CREATE SCHEMA s LOCATION %(v)s",
    "DROP DATABASE d -- %(v)s",
    "ALTER DATABASE d SET DBPROPERTIES ('k' = %(v)s)",
    # Leading comments must be stripped before detection on the Hive side too,
    # otherwise a commented Hive DDL statement would silently lose its escaping.
    "-- cleanup\nDROP TABLE t LOCATION %(v)s",
    "/* migrate */ ALTER TABLE t SET LOCATION %(v)s",
    "-- a\n-- b\nCREATE EXTERNAL TABLE t (c string) LOCATION %(v)s",
]


class TestDefaultParameterFormatter:
    def test_add_partition(self, formatter):
        expected = textwrap.dedent(
            """
            ALTER TABLE test_table
            ADD PARTITION (dt=DATE '2017-01-01', hour=1)
            """
        ).strip()

        actual = formatter.format(
            textwrap.dedent(
                """
                ALTER TABLE test_table
                ADD PARTITION (dt=%(dt)s, hour=%(hour)d)
                """
            ).strip(),
            {"dt": date(2017, 1, 1), "hour": 1},
        )
        assert actual == expected

